void divide_bloco(double **bloco, double divisor[8][8]) {
    if(bloco == NULL) return;
    
    for(int i = 0; i < 8; i++) {
        for(int j = 0; j < 8; j++)
            bloco[i][j] = round(bloco[i][j]/divisor[i][j]);
    }
}

void multiplica_bloco(double **bloco, double multiplicador[8][8]) {
    if(bloco == NULL) return;
    
    for(int i = 0; i < 8; i++) {
        for(int j = 0; j < 8; j++)
            bloco[i][j] = bloco[i][j]*multiplicador[i][j];
    }
}


